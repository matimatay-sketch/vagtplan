// Generates supabase/seeds/agreements.sql from the JSON templates.
// Run: pnpm --filter @vagtplan/agreements seed   (a test checks it is up to date)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "..", "supabase", "seeds", "agreements.sql");
const DOLLAR_TAG = "$agreement_doc$";

const sqlText = (s) => `'${String(s ?? "").replaceAll("'", "''")}'`;

export function render() {
  const docs = [
    "basis-dk/v1.json",
    "eksempel-detail/v1.json",
    "industriens-overenskomst/v1.json",
    "industriens-overenskomst/v2.json",
    "industriens-overenskomst/v3.json",
  ].map((f) => JSON.parse(readFileSync(join(root, f), "utf8")));
  const kits = ["industriens-overenskomst/startpakke.json"].map((f) =>
    JSON.parse(readFileSync(join(root, f), "utf8")),
  );
  const lines = [
    "-- GENERATED by packages/agreements/scripts/generate-seed.mjs – do not edit by hand.",
    "-- System agreement templates (organization_id is null).",
    "",
  ];
  for (const d of docs) {
    const json = JSON.stringify(d);
    if (json.includes(DOLLAR_TAG)) throw new Error("document contains the SQL dollar tag");
    const example = d.example ? "true" : "false";
    lines.push(
      "insert into public.agreement (organization_id, key, name, kind, is_example, description)",
      `select null, ${sqlText(d.id)}, ${sqlText(d.name)}, ${sqlText(d.kind)}, ${example}, ${sqlText(d.description)}`,
      `where not exists (select 1 from public.agreement where organization_id is null and key = ${sqlText(d.id)});`,
      `update public.agreement set name = ${sqlText(d.name)}, is_example = ${example}, description = ${sqlText(d.description)}`,
      `where organization_id is null and key = ${sqlText(d.id)};`,
      "insert into public.agreement_version (agreement_id, version, valid_from, valid_to, status, published_at, document)",
      `select a.id, ${d.version}, ${sqlText(d.valid_from)}, ${d.valid_to ? sqlText(d.valid_to) : "null"}, 'published', now(), ${DOLLAR_TAG}${json}${DOLLAR_TAG}::jsonb`,
      `from public.agreement a where a.organization_id is null and a.key = ${sqlText(d.id)}`,
      "on conflict (agreement_id, version) do update",
      "set document = excluded.document, valid_from = excluded.valid_from, valid_to = excluded.valid_to;",
      "",
    );
  }
  lines.push("-- Startpakker (chosen when a platform administrator creates a customer).", "");
  for (const k of kits) {
    const json = JSON.stringify(k);
    if (json.includes(DOLLAR_TAG)) throw new Error("starter kit contains the SQL dollar tag");
    lines.push(
      "insert into public.starter_kit (key, name, description, content)",
      `values (${sqlText(k.key)}, ${sqlText(k.name)}, ${sqlText(k.description)}, ${DOLLAR_TAG}${json}${DOLLAR_TAG}::jsonb)`,
      "on conflict (key) do update",
      "set name = excluded.name, description = excluded.description, content = excluded.content;",
      "",
    );
  }
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, render());
  console.log(`wrote ${out}`);
}
